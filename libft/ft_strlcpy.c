#include "libft.h"

size_t	ft_strlcpy(char *dest, const char *src, unsigned int size)
{
	unsigned int	i;
	unsigned int	l;

	l = 0;
	i = 0;
	while (src[l] != '\0')
	{
		l++;
	}
	if (size == 0)
	{
		return (l);
	}
	while (src[i] != '\0' && i < (size - 1))
	{
		dest[i] = src[i];
		i++;
	}
	dest[i] = '\0';
	return (l);
}
